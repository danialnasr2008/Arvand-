    <script>
    document.addEventListener('DOMContentLoaded', function() {
        initPageEvents();

        // Intercept global clicks
        document.addEventListener('click', function(e) {
            const link = e.target.closest('a');
            if (!link) return;

            const href = link.getAttribute('href');
            if (!href) return;

            // Exclude mailto, tel, absolute links to other sites, target _blank, class triggers, download files, or admin exports
            if (
                href.startsWith('/') && 
                !href.includes('/export') && 
                !href.includes('/logout') && 
                !link.hasAttribute('download') && 
                link.getAttribute('target') !== '_blank'
            ) {
                e.preventDefault();
                navigateTo(href);
            }
        });

        // Intercept all POST form submissions
        document.addEventListener('submit', function(e) {
            const form = e.target;
            if (form.getAttribute('method')?.toUpperCase() === 'POST' && !form.hasAttribute('enctype') && !form.classList.contains('no-ajax')) {
                e.preventDefault();
                
                const url = form.getAttribute('action') || window.location.pathname;
                const formData = new FormData(form);
                const progress = document.getElementById('loading-bar');
                
                if (progress) {
                    progress.style.width = '30%';
                    progress.style.opacity = '1';
                }

                fetch(url, {
                    method: 'POST',
                    body: formData
                })
                .then(response => {
                    if (progress) progress.style.width = '80%';
                    // Check if it redirected to export or full file download
                    if (response.headers.get('content-disposition')?.includes('attachment')) {
                        // Let it download
                        return null;
                    }
                    
                    // We can handle state redirect manually if we detected response url change
                    const responseUrl = new URL(response.url);
                    if (responseUrl.pathname !== window.location.pathname) {
                        window.history.pushState({ url: responseUrl.pathname }, '', responseUrl.pathname + responseUrl.search);
                    }
                    
                    return response.text();
                })
                .then(html => {
                    if (html === null) {
                        if (progress) {
                            progress.style.width = '100%';
                            setTimeout(() => { progress.style.opacity = '0'; }, 300);
                        }
                        return;
                    }
                    updateContent(html, progress);
                })
                .catch(err => {
                    console.error('Form submit error:', err);
                    form.submit(); // fallback
                });
            }
        });

        // Handle history navigation
        window.addEventListener('popstate', function(e) {
            if (e.state && e.state.url) {
                performFetch(e.state.url);
            } else {
                window.location.reload();
            }
        });
    });

    function navigateTo(url) {
        if (window.location.pathname + window.location.search === url) return;
        
        window.history.pushState({ url: url }, '', url);
        performFetch(url);
    }

    function performFetch(url) {
        const progress = document.getElementById('loading-bar');
        const mainContent = document.getElementById('main-content');
        
        if (progress) {
            progress.style.width = '20%';
            progress.style.opacity = '1';
        }
        if (mainContent) {
            mainContent.classList.add('opacity-40');
        }

        fetch(url)
            .then(response => {
                if (progress) progress.style.width = '70%';
                return response.text();
            })
            .then(html => {
                updateContent(html, progress);
            })
            .catch(err => {
                console.error('AJAX Load error:', err);
                window.location.href = url; // Fallback
            });
    }

    function updateContent(html, progress) {
        const mainContent = document.getElementById('main-content');
        const parser = new DOMParser();
        const doc = parser.parseFromString(html, 'text/html');

        // Update Title
        document.title = doc.title;

        // Update main container
        const newMain = doc.getElementById('main-content');
        if (newMain && mainContent) {
            mainContent.innerHTML = newMain.innerHTML;
            
            // Re-execute scripts to make elements interactive again
            const scripts = mainContent.querySelectorAll('script');
            scripts.forEach(oldScript => {
                const newScript = document.createElement('script');
                Array.from(oldScript.attributes).forEach(attr => newScript.setAttribute(attr.name, attr.value));
                newScript.appendChild(document.createTextNode(oldScript.innerHTML));
                oldScript.parentNode.replaceChild(newScript, oldScript);
            });

            // Smooth scroll
            window.scrollTo({ top: 0, behavior: 'smooth' });
        }

        // Keep active link or states updated in main header
        const currentHeader = document.querySelector('header');
        const newHeader = doc.querySelector('header');
        if (currentHeader && newHeader) {
            currentHeader.innerHTML = newHeader.innerHTML;
        }

        // Hide progress
        if (progress) {
            progress.style.width = '100%';
            setTimeout(() => {
                progress.style.opacity = '0';
                progress.style.width = '0%';
            }, 300);
        }

        if (mainContent) {
            mainContent.classList.remove('opacity-40');
        }

        // Rebind page events
        initPageEvents();
    }

    function initPageEvents() {
        // Initialize interactive modules like Tax calculator if present
        const formSubmitBtn = document.getElementById('calculator-btn');
        if (formSubmitBtn) {
            // Calculator exists on the loaded page, let's wire it up!
            formSubmitBtn.addEventListener('click', runTaxCalculator);
        }
    }

    function runTaxCalculator() {
        const incomeInput = document.getElementById('annual-income');
        const expensesInput = document.getElementById('annual-expenses');
        const resultDiv = document.getElementById('calc-result');
        const netProfitEl = document.getElementById('net-profit');
        const baseTaxEl = document.getElementById('base-tax');
        const taxRateEl = document.getElementById('tax-rate');
        const finalTaxEl = document.getElementById('final-tax');

        if (!incomeInput || !expensesInput || !resultDiv) return;

        const income = parseFloat(incomeInput.value) || 0;
        const expenses = parseFloat(expensesInput.value) || 0;

        if (income <= 0) {
            alert('لطفاً درآمد سالانه معتبری وارد کنید.');
            return;
        }

        const netProfit = Math.max(0, income - expenses);
        let taxRate = 0;
        let taxAmount = 0;

        // Simple Persian business tax brackets simulation
        if (netProfit <= 100000000) { // Up to 100M Tomans: 0% (exempt or basic floor)
            taxRate = 0;
        } else if (netProfit <= 300000000) { // 100M to 300M: 15%
            taxRate = 15;
            taxAmount = (netProfit - 100000000) * 0.15;
        } else if (netProfit <= 600000000) { // 300M to 600M: 20%
            taxRate = 20;
            taxAmount = (200000000 * 0.15) + ((netProfit - 300000000) * 0.20);
        } else { // Over 600M: 25%
            taxRate = 25;
            taxAmount = (200000000 * 0.15) + (300000000 * 0.20) + ((netProfit - 600000000) * 0.25);
        }

        if (netProfitEl) netProfitEl.textContent = formatCurrency(netProfit) + ' تومان';
        if (baseTaxEl) baseTaxEl.textContent = formatCurrency(taxAmount) + ' تومان';
        if (taxRateEl) taxRateEl.textContent = taxRate + ' درصد';
        if (finalTaxEl) finalTaxEl.textContent = formatCurrency(taxAmount) + ' تومان';

        resultDiv.classList.remove('hidden');
        resultDiv.scrollIntoView({ behavior: 'smooth' });
    }

    function formatCurrency(val) {
        return Math.round(val).toString().replace(/\B(?=(\d{3})+(?!\d))/g, "،");
    }
